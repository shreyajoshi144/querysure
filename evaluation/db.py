"""
Sample database provisioning for the evaluation.

The retail database is generated by the repository's own, unmodified
`create_retail.py` -- the same script the Dockerfile, render.yaml and
start.py use -- run in a *fresh interpreter* in a scratch directory.

A fresh process matters: create_retail.py seeds Python's `random` once at
import time, so calling create() twice in one process (or after other code
has consumed random numbers) would yield a different dataset. A subprocess
reproduces exactly what a deploy build produces.

Evaluation always runs against a private working copy, so it can never
modify a database the user points it at.
"""
from __future__ import annotations

import hashlib
import os
import shutil
import sqlite3
import subprocess
import sys
from typing import Optional

from . import REPO_ROOT


class DatabaseError(RuntimeError):
    pass


def build_sample_db(dest_dir: str) -> str:
    """Generate retail.db inside dest_dir via the repo's create_retail.py."""
    script = os.path.join(REPO_ROOT, "create_retail.py")
    if not os.path.exists(script):
        raise DatabaseError(f"create_retail.py not found at {script}")
    os.makedirs(dest_dir, exist_ok=True)
    shutil.copy(script, dest_dir)
    env = dict(os.environ, PYTHONWARNINGS="ignore", PYTHONIOENCODING="utf-8")
    proc = subprocess.run(
        [sys.executable, "create_retail.py"], cwd=dest_dir,
        capture_output=True, text=True, env=env,
    )
    if proc.returncode != 0:
        raise DatabaseError(f"create_retail.py failed:\n{proc.stdout}\n{proc.stderr}")
    path = os.path.join(dest_dir, "retail.db")
    if not os.path.exists(path):
        raise DatabaseError("create_retail.py ran but produced no retail.db")
    return path


def prepare_database(db_path: Optional[str], workdir: str) -> str:
    """Return the path of a private, disposable database to evaluate against.

    db_path=None  -> build the standard sample retail DB.
    db_path=<file> -> copy that database (never touch the original).
    """
    if db_path is None:
        return build_sample_db(os.path.join(workdir, "sample"))
    if not os.path.isfile(db_path):
        raise DatabaseError(f"database not found: {db_path}")
    dest = os.path.join(workdir, "copy")
    os.makedirs(dest, exist_ok=True)
    target = os.path.join(dest, os.path.basename(db_path))
    shutil.copy(db_path, target)
    return target


def open_readonly(db_path: str) -> sqlite3.Connection:
    return sqlite3.connect(f"file:{db_path}?mode=ro", uri=True)


def db_fingerprint(db_path: str) -> str:
    """Content hash of every user table (schema + rows in rowid order)."""
    h = hashlib.sha256()
    conn = open_readonly(db_path)
    try:
        tables = [r[0] for r in conn.execute(
            "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name")]
        for t in tables:
            h.update(t.encode())
            h.update(repr(conn.execute(f'PRAGMA table_info("{t}")').fetchall()).encode())
            for row in conn.execute(f'SELECT * FROM "{t}" ORDER BY rowid'):
                h.update(repr(row).encode())
    finally:
        conn.close()
    return h.hexdigest()
